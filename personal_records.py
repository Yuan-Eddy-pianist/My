"""Validated personal-agenda edits; persistence belongs to firstmate_context.py."""
from copy import deepcopy
from datetime import date
from pathlib import Path
import uuid

COLLECTIONS = ('projects', 'tasks', 'reminders')
FIELDS = {
    'projects': {'title', 'path', 'status', 'goal', 'progress'},
    'tasks': {'title', 'due', 'status', 'notes'},
    'reminders': {'title', 'due', 'status', 'notes'},
}


def check_workspace(data):
    if not isinstance(data, dict):
        raise ValueError('Workspace must be an object')
    for kind in COLLECTIONS:
        records = data.get(kind)
        if not isinstance(records, list):
            raise ValueError(f'Workspace is missing the {kind} array')
        ids = set()
        for item in records:
            if not isinstance(item, dict) or not isinstance(item.get('id'), str) or not item['id']:
                raise ValueError(f'Invalid {kind} record identity')
            if item['id'] in ids:
                raise ValueError(f'Duplicate {kind} id: {item["id"]}')
            ids.add(item['id'])


def validate_fields(kind, fields):
    if not isinstance(fields, dict) or not fields or fields.keys() - FIELDS[kind]:
        raise ValueError(f'Provide editable {kind} fields only: {sorted(FIELDS[kind])}')
    for key, value in fields.items():
        if key == 'due':
            if value is None and kind == 'tasks':
                continue
            if not isinstance(value, str):
                raise ValueError('due must be YYYY-MM-DD (tasks also accept null)')
            try:
                if date.fromisoformat(value).isoformat() != value:
                    raise ValueError()
            except ValueError:
                raise ValueError('due must be a valid YYYY-MM-DD') from None
        elif not isinstance(value, str):
            raise ValueError(f'{key} must be a string')
        elif key == 'title' and not value.strip():
            raise ValueError('title must not be empty')
        elif key == 'path' and not Path(value).is_absolute():
            raise ValueError('Project path must be absolute; ask the user if unknown')
        elif key == 'status' and value not in (
            ('active', 'paused', 'done') if kind == 'projects' else ('open', 'done')
        ):
            raise ValueError(f'Invalid {kind} status')


def apply_operations(workspace, operations, now):
    """Return a new workspace; a bad operation rejects the entire batch."""
    check_workspace(workspace)
    if not isinstance(operations, list) or not 1 <= len(operations) <= 100:
        raise ValueError('operations must contain between 1 and 100 edits')
    result = deepcopy(workspace)
    changes = []
    for op in operations:
        if not isinstance(op, dict) or op.keys() - {'op', 'collection', 'id', 'fields'}:
            raise ValueError('Invalid operation shape')
        action, kind = op.get('op'), op.get('collection')
        if action not in ('add', 'update', 'delete') or kind not in COLLECTIONS:
            raise ValueError('Expected add/update/delete and projects/tasks/reminders')
        records = result[kind]
        if action == 'add':
            if 'id' in op:
                raise ValueError('New record IDs are generated by the server')
            fields = op.get('fields')
            validate_fields(kind, fields)
            required = {'title', 'path'} if kind == 'projects' else {'title'}
            if kind == 'reminders':
                required.add('due')
            if required - fields.keys():
                raise ValueError(f'Missing fields: {sorted(required - fields.keys())}')
            item = {'id': uuid.uuid4().hex, 'created': now}
            item.update({'status': 'active', 'goal': '', 'progress': '', 'updated': now}
                        if kind == 'projects' else {'status': 'open', 'due': None, 'notes': ''})
            item.update(fields)
            records.append(item)
        else:
            if not isinstance(op.get('id'), str) or not op['id']:
                raise ValueError('Existing record id required')
            item = next((item for item in records if item['id'] == op['id']), None)
            if item is None:
                raise ValueError(f'No {kind} record with id {op["id"]}')
            if action == 'delete':
                if 'fields' in op:
                    raise ValueError('delete does not accept fields')
                records.remove(item)
            else:
                fields = op.get('fields')
                validate_fields(kind, fields)
                item.update(fields)
                if kind == 'projects':
                    item['updated'] = now
        changes.append({'op': action, 'collection': kind, 'id': item['id']})
    return result, changes
